#!/usr/bin/env python3
"""Turn (procedural, restyled) teacher pairs into a musubi-tuner Qwen-Image-Edit dataset.

The restyled image is the training target (`images/`). The procedural render is the
control (`controls/`), same filename. Captions live next to the targets.

Teacher tiles must be OUR renders restyled by OUR prompt. This script will refuse
to copy a directory that looks like a third-party style-reference dump.

Usage:

    python3 lora/prepare_dataset.py \
        --teacher /workspace/tinysz-teacher \
        --out /workspace/tinysz-teacher/dataset
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = Path(__file__).resolve().parent / "teacher-manifest.json"

# Same wording used at LoRA inference time. Describes the look; does not name a third-party map.
CAPTION = (
    "Redraw this isometric city view as detailed isometric pixel art in a fine naturalistic miniature style. "
    "Keep the exact camera, 2:1 dimetric projection, building footprints, heights, roof shapes, streets, parks, water and tree positions. "
    "Muted warm-grey and beige concrete towers; teal-green and sky-blue glass curtain walls with sky reflections and very fine window grids. "
    "Pastel mid-rises in cream, pale pink and pale blue, terracotta low roofs, lush rounded tree canopies, teal-green water, grey asphalt roads with markings. "
    "No cartoon ink outlines. Natural daylight from the upper left, soft cool shadows. Tilt-shift miniature feel."
)


def _refuse_third_party(teacher: Path) -> None:
    text = " ".join(p.name.lower() for p in teacher.rglob("*") if p.is_file())
    banned = ("yadong", "pixel-singapore", "pixelsingapore", "pixel_singapore")
    if any(b in text for b in banned):
        raise SystemExit(
            f"refusing {teacher}: filenames look like a third-party map dump. "
            "Train only on our own teacher tiles."
        )


def prepare(teacher: Path, out: Path, manifest_path: Path, size: int = 1024) -> int:
    _refuse_third_party(teacher)
    man = json.loads(manifest_path.read_text())
    windows = man["windows"]
    proc = teacher / "procedural"
    rest = teacher / "restyled"
    images = out / "images"
    controls = out / "controls"
    cache = out / "cache"
    for d in (images, controls, cache):
        d.mkdir(parents=True, exist_ok=True)

    n = 0
    missing: list[str] = []
    for win in windows:
        pid = win["id"]
        src = proc / f"{pid}.png"
        dst = rest / f"{pid}.png"
        if not src.exists() or not dst.exists():
            missing.append(pid)
            continue
        for path, label in ((src, "procedural"), (dst, "restyled")):
            with Image.open(path) as im:
                if im.size != (size, size):
                    raise SystemExit(f"{label} {path.name} is {im.size}, expected {size}×{size}")
        shutil.copy2(dst, images / f"{pid}.png")
        shutil.copy2(src, controls / f"{pid}.png")
        (images / f"{pid}.txt").write_text(CAPTION + "\n")
        n += 1

    if not n:
        raise SystemExit(f"no complete pairs in {teacher} (missing: {missing[:8]}…)")

    images_dir = images.resolve()
    controls_dir = controls.resolve()
    cache_dir = cache.resolve()
    toml = f"""# musubi-tuner dataset for a Qwen-Image-Edit-2511 LoRA.
# Targets (restyled) in image_directory, procedural controls in control_directory.
# Generated by lora/prepare_dataset.py — {n} pairs.

[general]
resolution = [1024, 1024]
caption_extension = ".txt"
batch_size = 1
enable_bucket = false
num_repeats = 2

[[datasets]]
image_directory = "{images_dir}"
control_directory = "{controls_dir}"
cache_directory = "{cache_dir}"
control_resolution = [1024, 1024]
no_resize_control = false
"""
    (out / "dataset.toml").write_text(toml)
    (out / "caption.txt").write_text(CAPTION + "\n")
    print(f"prepare_dataset: {n} pairs → {out} ({len(missing)} windows skipped, incomplete)", flush=True)
    if missing:
        print("  skipped: " + ", ".join(missing), flush=True)
    return n


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--teacher", type=Path, default=Path("/workspace/tinysz-teacher"))
    ap.add_argument("--out", type=Path, default=Path("/workspace/tinysz-teacher/dataset"))
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--size", type=int, default=1024)
    args = ap.parse_args()
    prepare(args.teacher, args.out, args.manifest, args.size)


if __name__ == "__main__":
    main()
