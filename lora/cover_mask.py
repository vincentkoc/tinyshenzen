"""Write the viewer's cover mask: which parts of the edge tiles lie inside the outline.

The night layer in the viewer only lights what is inside the map's coverage outline. Tiles
well inside it are whole; the tiles the outline crosses are split into CELLS × CELLS cells,
and a cell counts when its centre lies at least half a cell inside the outline. The result
is a TypeScript module the viewer loads with the night layer (never on first load):

    python lora/cover_mask.py --outline coverage.geojson \\
        --manifest tinyworlds-frontend/public/data/tinysz-core/manifest.json \\
        --out tinyworlds-frontend/src/worlds/tinysz-core.cover.ts

Re-run it whenever the outline or the manifest's tile set changes.
"""

from __future__ import annotations

import argparse
import base64
import json
import math
from pathlib import Path

import numpy as np

from coverage import Outline, load_rings, project_rings

CELLS = 8


def decode_bitset(b64: str) -> bytes:
    return base64.b64decode(b64)


def has_tile(bits: bytes, cols: int, tx: int, ty: int) -> bool:
    i = tx + ty * cols
    return bool(bits[i >> 3] & (1 << (i & 7)))


def pack_cells(inside: np.ndarray) -> str:
    """Row-major, LSB-first bits (the manifest's bitset order), base64."""
    flat = inside.astype(bool).reshape(-1)
    out = bytearray((flat.size + 7) // 8)
    for i, on in enumerate(flat):
        if on:
            out[i >> 3] |= 1 << (i & 7)
    return base64.b64encode(bytes(out)).decode("ascii")


def cover_mask(outline: Outline, manifest: dict, cells: int = CELLS) -> dict[str, str]:
    """`"tx_ty"` → packed cells for every present z0 tile the outline reaches into."""
    tile = int(manifest["tileSize"])
    level = next(l for l in manifest["levels"] if l["z"] == 0)
    cols, rows = level["cols"], level["rows"]
    bits = decode_bitset(level["tiles"])
    cell = tile / cells
    half_diag = tile * math.sqrt(2) / 2
    present = [(tx, ty) for ty in range(rows) for tx in range(cols) if has_tile(bits, cols, tx, ty)]
    if not present:
        return {}
    cx = np.array([tx * tile + tile / 2 for tx, _ in present], dtype=np.float64)
    cy = np.array([ty * tile + tile / 2 for _, ty in present], dtype=np.float64)
    centre = outline.signed(cx, cy)
    offs = (np.arange(cells) + 0.5) * cell
    out: dict[str, str] = {}
    for (tx, ty), sd in zip(present, centre):
        if sd < -(half_diag + cell):
            continue  # whole tile inside
        gx, gy = np.meshgrid(tx * tile + offs, ty * tile + offs)
        inside = outline.signed(gx, gy) <= -cell / 2
        if inside.all():
            continue
        out[f"{tx}_{ty}"] = pack_cells(inside)
    return out


def write_module(path: Path, mask: dict[str, str], cells: int) -> None:
    lines = [
        "// Generated by lora/cover_mask.py; do not edit by hand.",
        'import type { CoverMask } from "./types";',
        "",
        "export const COVER: CoverMask = {",
        f"  cells: {cells},",
        "  tiles: {",
    ]
    lines += [f'    "{k}": "{v}",' for k, v in sorted(mask.items())]
    lines += ["  },", "};", ""]
    path.write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--outline", type=Path, required=True)
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--cells", type=int, default=CELLS)
    args = ap.parse_args()
    manifest = json.loads(args.manifest.read_text())
    origin = (float(manifest["origin"]["x"]), float(manifest["origin"]["y"]))
    rings = project_rings(load_rings(args.outline), manifest["geo"], origin)
    mask = cover_mask(Outline(rings), manifest, args.cells)
    write_module(args.out, mask, args.cells)
    print(f"cover mask: {len(mask)} edge tiles, {args.cells}×{args.cells} cells → {args.out}")


if __name__ == "__main__":
    main()
