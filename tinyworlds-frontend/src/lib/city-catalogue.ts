/**
 * Cities a donor is likely to ask for, so most people can pick one instead of typing it (and so
 * "London" and "Londres" end up as the same city). `name` is what is sent and stored: the usual
 * English name. `cc` is the ISO 3166 alpha-2 country, shown through `Intl.DisplayNames` in the
 * visitor's language. `alt` lists other spellings people type, mostly the Portuguese and Spanish
 * names; they only help the search.
 */
export interface CatalogueCity {
  name: string;
  cc: string;
  alt?: string[];
}

const city = (name: string, cc: string, ...alt: string[]): CatalogueCity =>
  alt.length > 0 ? { name, cc, alt } : { name, cc };

